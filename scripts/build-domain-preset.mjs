import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const glossaryDir = path.join(projectRoot, 'quant_scholar_translator', 'data', 'glossaries');
const output = path.join(projectRoot, 'apps', 'browser-extension', 'research', 'domain-preset.mjs');
const babelDocOutput = path.join(projectRoot, 'quant_scholar_translator', 'data', 'babeldoc-professional.csv');
const files = fs.readdirSync(glossaryDir).filter(name => name.endsWith('.json')).sort();
const seen = new Set();
const terms = [];
for (const file of files) {
  const domain = path.basename(file, '.json');
  for (const item of JSON.parse(fs.readFileSync(path.join(glossaryDir, file), 'utf8'))) {
    const key = String(item.source).toLocaleLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    terms.push({ source: item.source, target: item.target, domain });
  }
}
const body = `// Generated by scripts/build-domain-preset.mjs. Do not edit manually.\n`
  + `export const QUANT_SCHOLAR_GLOSSARY_PRESET = Object.freeze(${JSON.stringify(terms, null, 2)}.map(Object.freeze));\n`;
fs.writeFileSync(output, body, 'utf8');
const csvCell = value => `"${String(value ?? '').replaceAll('"', '""')}"`;
const csv = ['source,target,tgt_lng', ...terms.map(item =>
  [item.source, item.target, 'zh'].map(csvCell).join(','))].join('\n') + '\n';
fs.writeFileSync(babelDocOutput, csv, 'utf8');
console.log(`Generated ${terms.length} professional terms`);
