import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const glossaryDir = path.join(projectRoot, 'quant_scholar_translator', 'data', 'glossaries');
const output = path.join(projectRoot, 'apps', 'browser-extension', 'research', 'domain-preset.mjs');
const babelDocOutput = path.join(projectRoot, 'quant_scholar_translator', 'data', 'babeldoc-professional.csv');
const files = fs.readdirSync(glossaryDir).filter(name => name.endsWith('.json')).sort();
const seen = new Set();
const terms = [];
for (const file of files) {
  const domain = path.basename(file, '.json');
  for (const item of JSON.parse(fs.readFileSync(path.join(glossaryDir, file), 'utf8'))) {
    if (!item.source?.trim() || !item.target?.trim() || !item.note?.trim()) throw new Error(`Invalid glossary entry in ${file}`);
    if (item.aliases && (!Array.isArray(item.aliases) || item.aliases.some(a => typeof a !== 'string' || !a.trim()))) throw new Error(`Invalid aliases in ${file}`);
    const key = `${domain}:${String(item.source).trim().toLowerCase()}`;
    if (seen.has(key)) throw new Error(`Duplicate glossary entry: ${key}`);
    seen.add(key);
    terms.push({ ...item, domain });
  }
}
const body = `// Generated by scripts/build-domain-preset.mjs. Do not edit manually.\n`
  + `export const QUANT_SCHOLAR_GLOSSARY_PRESET = Object.freeze(${JSON.stringify(terms, null, 2)}.map(Object.freeze));\n`;
fs.writeFileSync(output, body, 'utf8');
const csvCell = value => `"${String(value ?? '').replaceAll('"', '""')}"`;
// Flat replacement CSV has no domain/context support: omit ambiguous words.
const targets = new Map();
for (const item of terms) { const key = item.source.toLowerCase(); if (!targets.has(key)) targets.set(key, new Set()); targets.get(key).add(item.target); }
const flatSeen = new Set();
const flatTerms = terms.filter(item => {
  const key = item.source.toLowerCase();
  if (targets.get(key).size > 1 || flatSeen.has(key)) return false;
  flatSeen.add(key); return true;
});
const csv = ['source,target,tgt_lng', ...flatTerms.map(item =>
  [item.source, item.target, 'zh'].map(csvCell).join(','))].join('\n') + '\n';
fs.writeFileSync(babelDocOutput, csv, 'utf8');
console.log(`Generated ${terms.length} contextual terms; ${flatTerms.length} unambiguous CSV terms`);
